import { open } from 'node:fs/promises';
import { parseSpacedDuration } from './duration.js';
import { normalizeHexColor } from './tags.js';

/**
 * Reads slicer metadata from G-code comments. Only the head (header and
 * thumbnails) and the tail (totals and the config block) are read, so
 * multi-hundred-MB files never load into memory. Verified against
 * OrcaSlicer 2.3–2.4 and Creality Print 5.1 and 6.3 output.
 */
export interface GcodeSlot {
  /** 1-based slot (extruder / CFS slot) number. */
  slot: number;
  grams: number;
  /** #rrggbb from filament_colour, when present. */
  colour: string | null;
  /** From filament_type, e.g. "PLA". */
  material: string | null;
}

export interface GcodeThumbnail {
  format: 'png' | 'jpg' | 'qoi';
  width: number;
  height: number;
  data: Buffer;
}

export interface GcodeMetadata {
  slicer: { name: string; version: string } | null;
  /** Total filament in grams: the "total" line when present, else the sum of the slots. */
  totalGrams: number | null;
  /** Slots that used filament (grams > 0). */
  slots: GcodeSlot[];
  printTimeSeconds: number | null;
  printerModel: string | null;
  thumbnails: GcodeThumbnail[];
}

export interface GcodeText {
  head: string;
  /** Empty when `head` already holds the whole file. */
  tail: string;
}

export const DEFAULT_WINDOW_BYTES = 64 * 1024;
/** Upper bound when the head window is extended to finish a thumbnail. */
const MAX_HEAD_BYTES = 4 * 1024 * 1024;
/** Upper bound when the tail window is widened to reach the totals. */
const MAX_TAIL_BYTES = 1024 * 1024;
/** Lines that mark the start of the metadata tail. */
const TAIL_MARKER = /^;\s*(?:total\s+)?filament used \[g\]|EXECUTABLE_BLOCK_END/im;

const THUMBNAIL_BEGIN = /^;\s*thumbnail(?:_(PNG|JPG|QOI))?\s+begin\s+(\d+)x(\d+)\s+(\d+)\s*$/i;
const THUMBNAIL_END = /^;\s*thumbnail(?:_(?:PNG|JPG|QOI))?\s+end\s*$/i;
const GRAMS = /^;\s*(total\s+)?filament used \[g\]\s*=\s*(.+)$/i;
const PRINT_TIME = /^;\s*estimated printing time(?:\s*\(normal mode\))?\s*=\s*(.+)$/i;
const GENERATED_BY = /^;\s*generated by\s+(.+?)\s+(\S+)\s+on\s/i;
const KEY_VALUE = /^;\s*([a-z_][a-z0-9_]*)\s*=\s*(.*)$/i;

/** Printer model keys in order of preference (brief §2.3). */
const PRINTER_KEYS = [
  'printer_model',
  'print_compatible_printers',
  'printer_settings_id',
  'printer_prefix',
] as const;

export function parseGcodeText({ head, tail }: GcodeText): GcodeMetadata {
  const lines = [...head.split(/\r?\n/), ...tail.split(/\r?\n/)];
  const values = new Map<string, string>();
  let slicer: GcodeMetadata['slicer'] = null;
  let total: number | null = null;
  let perSlot: number[] | null = null;
  let printTimeSeconds: number | null = null;

  for (const line of lines) {
    if (!line.startsWith(';')) continue;

    const grams = GRAMS.exec(line);
    if (grams !== null) {
      const numbers = parseNumberList(grams[2] ?? '');
      if (grams[1] !== undefined) total = numbers.reduce((sum, n) => sum + n, 0);
      else perSlot = numbers;
      continue;
    }

    const time = PRINT_TIME.exec(line);
    if (time !== null) {
      printTimeSeconds ??= parseSpacedDuration(time[1] ?? '');
      continue;
    }

    if (slicer === null) {
      const generated = GENERATED_BY.exec(line);
      if (generated?.[1] !== undefined && generated[2] !== undefined) {
        slicer = { name: generated[1], version: generated[2] };
        continue;
      }
    }

    const kv = KEY_VALUE.exec(line);
    if (kv?.[1] !== undefined) values.set(kv[1].toLowerCase(), (kv[2] ?? '').trim());
  }

  const colours = splitList(values.get('filament_colour'));
  const materials = splitList(values.get('filament_type'));
  const slots: GcodeSlot[] = (perSlot ?? []).flatMap((grams, index) =>
    grams > 0
      ? [
          {
            slot: index + 1,
            grams,
            colour: normalizeHexColor(colours[index]),
            material: emptyToNull(materials[index]),
          },
        ]
      : [],
  );

  const slotSum = perSlot === null ? null : roundGrams(perSlot.reduce((s, n) => s + n, 0));
  return {
    slicer,
    totalGrams: total === null ? slotSum : roundGrams(total),
    slots,
    printTimeSeconds,
    printerModel: firstPrinterModel(values),
    thumbnails: extractThumbnails(head),
  };
}

/**
 * Reads the head and tail windows of a G-code file. Small files are read
 * whole. When a thumbnail starts in the head window but does not end there,
 * the head is extended to the size the thumbnail header announces.
 */
export async function readGcodeFile(
  filePath: string,
  windowBytes: number = DEFAULT_WINDOW_BYTES,
): Promise<GcodeMetadata> {
  const handle = await open(filePath, 'r');
  try {
    const { size } = await handle.stat();
    if (size <= windowBytes * 2) {
      return parseGcodeText({
        head: (await readRange(handle, 0, size)).toString('utf8'),
        tail: '',
      });
    }

    let headBytes = windowBytes;
    let head = await readRange(handle, 0, headBytes);
    const wanted = Math.min(requiredHeadBytes(head.toString('utf8')), MAX_HEAD_BYTES, size);
    if (wanted > headBytes) {
      headBytes = wanted;
      head = await readRange(handle, 0, headBytes);
    }

    // The totals sit just above the config block; widen the tail until it includes them.
    let tailBytes = windowBytes;
    let tailStart = Math.max(headBytes, size - tailBytes);
    let tail = await readRange(handle, tailStart, size - tailStart);
    while (
      !TAIL_MARKER.test(tail.toString('utf8')) &&
      tailStart > headBytes &&
      tailBytes < MAX_TAIL_BYTES
    ) {
      tailBytes *= 2;
      tailStart = Math.max(headBytes, size - tailBytes);
      tail = await readRange(handle, tailStart, size - tailStart);
    }
    return parseGcodeText({
      head: dropPartialLastLine(head.toString('utf8')),
      tail:
        tailStart === headBytes
          ? tail.toString('utf8')
          : dropPartialFirstLine(tail.toString('utf8')),
    });
  } finally {
    await handle.close();
  }
}

/** The largest PNG or JPG thumbnail, or null. QOI is not usable in browsers. */
export function bestThumbnail(thumbnails: readonly GcodeThumbnail[]): GcodeThumbnail | null {
  return (
    thumbnails
      .filter((t) => t.format !== 'qoi')
      .reduce<GcodeThumbnail | null>(
        (best, t) => (best === null || t.width * t.height > best.width * best.height ? t : best),
        null,
      ) ?? null
  );
}

function extractThumbnails(head: string): GcodeThumbnail[] {
  const thumbnails: GcodeThumbnail[] = [];
  let current: {
    format: GcodeThumbnail['format'];
    width: number;
    height: number;
    parts: string[];
  } | null = null;

  for (const line of head.split(/\r?\n/)) {
    const begin = THUMBNAIL_BEGIN.exec(line);
    if (begin !== null) {
      current = {
        format: (begin[1]?.toLowerCase() ?? 'png') as GcodeThumbnail['format'],
        width: Number(begin[2]),
        height: Number(begin[3]),
        parts: [],
      };
      continue;
    }
    if (current === null) continue;
    if (THUMBNAIL_END.test(line)) {
      const data = Buffer.from(current.parts.join(''), 'base64');
      if (hasValidSignature(current.format, data)) {
        thumbnails.push({
          format: current.format,
          width: current.width,
          height: current.height,
          data,
        });
      }
      current = null;
      continue;
    }
    current.parts.push(line.replace(/^;\s?/, '').trim());
  }
  return thumbnails;
}

/** Bytes needed to include an unfinished thumbnail block in the head window. */
function requiredHeadBytes(head: string): number {
  let required = 0;
  let open: { offset: number; base64Length: number } | null = null;
  let offset = 0;
  for (const line of head.split('\n')) {
    const begin = THUMBNAIL_BEGIN.exec(line.trimEnd());
    if (begin !== null) open = { offset, base64Length: Number(begin[4]) };
    else if (open !== null && THUMBNAIL_END.test(line.trimEnd())) open = null;
    offset += Buffer.byteLength(line) + 1;
  }
  if (open !== null) {
    // Base64 is split into short comment lines ("; " + up to 78 chars + newline).
    required = open.offset + Math.ceil(open.base64Length * 1.1) + 4096;
  }
  return required;
}

function hasValidSignature(format: GcodeThumbnail['format'], data: Buffer): boolean {
  if (format === 'png') return data.subarray(0, 8).equals(PNG_SIGNATURE);
  if (format === 'jpg') return data[0] === 0xff && data[1] === 0xd8;
  return data.subarray(0, 4).toString('latin1') === 'qoif';
}

const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

function firstPrinterModel(values: ReadonlyMap<string, string>): string | null {
  for (const key of PRINTER_KEYS) {
    const first = splitList(values.get(key))[0];
    if (first !== undefined && first !== '') return first;
  }
  return null;
}

/** Splits "a;b" or "\"a\";\"b\"" lists and strips quotes. */
function splitList(value: string | undefined): string[] {
  if (value === undefined || value.trim() === '') return [];
  return value.split(';').map((item) =>
    item
      .trim()
      .replace(/^"(.*)"$/, '$1')
      .trim(),
  );
}

function parseNumberList(text: string): number[] {
  return text
    .split(',')
    .map((part) => Number.parseFloat(part.trim()))
    .filter((n) => Number.isFinite(n) && n >= 0);
}

function emptyToNull(value: string | undefined): string | null {
  return value === undefined || value === '' ? null : value;
}

function roundGrams(value: number): number {
  return Math.round(value * 100) / 100;
}

async function readRange(
  handle: Awaited<ReturnType<typeof open>>,
  position: number,
  length: number,
): Promise<Buffer> {
  const buffer = Buffer.alloc(length);
  const { bytesRead } = await handle.read(buffer, 0, length, position);
  return buffer.subarray(0, bytesRead);
}

function dropPartialLastLine(text: string): string {
  const end = text.lastIndexOf('\n');
  return end === -1 ? '' : text.slice(0, end);
}

function dropPartialFirstLine(text: string): string {
  const start = text.indexOf('\n');
  return start === -1 ? '' : text.slice(start + 1);
}
